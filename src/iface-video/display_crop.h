#ifndef MZ800EMU_DISPLAY_CROP_H
#define MZ800EMU_DISPLAY_CROP_H

#include "hw-generic/gdg/video.h"

/* Host presentation only. Preserve the complete emulated raster and canvas.
 * MZ-800 retains half of each physical border; other architectures unchanged. */
#if MZARCH == 800
#define VIDEO_UI_CROP_LEFT (VIDEO_BORDER_LEFT_WIDTH / 2)
#define VIDEO_UI_CROP_RIGHT (VIDEO_BORDER_RIGHT_WIDTH / 2)
#define VIDEO_UI_CROP_TOP (VIDEO_BORDER_TOP_HEIGHT / 2)
#define VIDEO_UI_CROP_BOTTOM (VIDEO_BORDER_BOTOM_HEIGHT / 2)
#else
#define VIDEO_UI_CROP_LEFT 0
#define VIDEO_UI_CROP_RIGHT 0
#define VIDEO_UI_CROP_TOP 0
#define VIDEO_UI_CROP_BOTTOM 0
#endif

#define VIDEO_UI_DISPLAY_WIDTH (VIDEO_DISPLAY_WIDTH - VIDEO_UI_CROP_LEFT - VIDEO_UI_CROP_RIGHT)
#define VIDEO_UI_DISPLAY_HEIGHT (VIDEO_DISPLAY_HEIGHT - VIDEO_UI_CROP_TOP - VIDEO_UI_CROP_BOTTOM)
#define VIDEO_UI_U0 ((float)VIDEO_UI_CROP_LEFT / VIDEO_DISPLAY_WIDTH)
#define VIDEO_UI_V0 ((float)VIDEO_UI_CROP_TOP / VIDEO_DISPLAY_HEIGHT)
#define VIDEO_UI_U1 ((float)(VIDEO_DISPLAY_WIDTH - VIDEO_UI_CROP_RIGHT) / VIDEO_DISPLAY_WIDTH)
#define VIDEO_UI_V1 ((float)(VIDEO_DISPLAY_HEIGHT - VIDEO_UI_CROP_BOTTOM) / VIDEO_DISPLAY_HEIGHT)

#endif
